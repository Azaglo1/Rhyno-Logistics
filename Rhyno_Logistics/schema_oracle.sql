-- Oracle (SQL*Plus) schema for Rhyno Logistics.
-- Bootstrap only: if any application tables already exist, this script exits
-- rather than deleting or replacing existing customer and booking data.
-- Run as: sqlplus user/pass@//host:1521/service @schema_oracle.sql

WHENEVER SQLERROR EXIT SQL.SQLCODE

BEGIN
  DECLARE
    existing_tables NUMBER;
  BEGIN
    SELECT COUNT(*) INTO existing_tables FROM user_tables
    WHERE table_name IN ('NOTIFICATIONS','PAYMENTS','QUOTATIONS','TRACKING_HISTORY',
      'SHIPMENTS','PASSENGERS','BOOKINGS','ADMINISTRATORS','CUSTOMERS');
    IF existing_tables > 0 THEN
      RAISE_APPLICATION_ERROR(-20001,
        'Rhyno tables already exist. Bootstrap stopped to protect existing data.');
    END IF;
  END;
END;
/

CREATE TABLE customers (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(255) NOT NULL,
  email         VARCHAR2(255) NOT NULL,
  phone         VARCHAR2(50)  NOT NULL,
  password_hash VARCHAR2(255) NOT NULL,
  session_version NUMBER(10) DEFAULT 0 NOT NULL,
  active        NUMBER(1) DEFAULT 1 NOT NULL,
  password_reset_token_hash VARCHAR2(64),
  password_reset_expires_at TIMESTAMP WITH TIME ZONE,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_customers_email UNIQUE (email),
  CONSTRAINT ck_customers_active CHECK (active IN (0, 1))
);

CREATE TABLE administrators (
  id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(255) NOT NULL,
  email         VARCHAR2(255) NOT NULL,
  password_hash VARCHAR2(255) NOT NULL,
  session_version NUMBER(10) DEFAULT 0 NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_administrators_email UNIQUE (email)
);

CREATE TABLE bookings (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference   VARCHAR2(50) NOT NULL,
  customer_id NUMBER,
  category    VARCHAR2(50) NOT NULL,
  status      VARCHAR2(50) NOT NULL,
  payload     CLOB DEFAULT '{}' NOT NULL,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_bookings_reference UNIQUE (reference),
  CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

CREATE TABLE passengers (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id  NUMBER NOT NULL,
  name        VARCHAR2(255) NOT NULL,
  email       VARCHAR2(255),
  phone       VARCHAR2(50),
  nationality VARCHAR2(100),
  CONSTRAINT fk_passengers_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);

CREATE TABLE shipments (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tracking_number VARCHAR2(50) NOT NULL,
  booking_id      NUMBER,
  origin          VARCHAR2(255) NOT NULL,
  destination     VARCHAR2(255) NOT NULL,
  status          VARCHAR2(50)  NOT NULL,
  eta             TIMESTAMP WITH TIME ZONE,
  location        VARCHAR2(255),
  updated_at      TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT uq_shipments_tracking UNIQUE (tracking_number),
  CONSTRAINT fk_shipments_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);

CREATE TABLE tracking_history (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  shipment_id NUMBER NOT NULL,
  status      VARCHAR2(50)  NOT NULL,
  location    VARCHAR2(255) NOT NULL,
  occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_history_shipment FOREIGN KEY (shipment_id) REFERENCES shipments(id)
);

CREATE TABLE quotations (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id NUMBER NOT NULL,
  status     VARCHAR2(50) NOT NULL,
  amount     NUMBER(12,2),
  currency   VARCHAR2(10),
  notes      CLOB,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_quotations_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);

CREATE TABLE payments (
  id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id NUMBER NOT NULL,
  amount     NUMBER(12,2) NOT NULL,
  currency   VARCHAR2(3),
  status     VARCHAR2(50)  NOT NULL,
  provider   VARCHAR2(100) NOT NULL,
  provider_reference VARCHAR2(100),
  provider_checkout_url VARCHAR2(1000),
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE,
  CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings(id)
);

CREATE UNIQUE INDEX uq_customers_reset_hash ON customers(password_reset_token_hash);
CREATE UNIQUE INDEX uq_payments_provider_ref ON payments(provider_reference);

CREATE TABLE notifications (
  id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER,
  message     CLOB NOT NULL,
  read_at     TIMESTAMP WITH TIME ZONE,
  created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT fk_notifications_customer FOREIGN KEY (customer_id) REFERENCES customers(id)
);

COMMIT;

PROMPT Schema created successfully.
